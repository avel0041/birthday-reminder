    private static String getRandomElement(String[] ar) {
        return ar[rand.nextInt(ar.length)];
    }

    private static LocalDate getRandomDate(){
        int minAge = 7;
        int maxAge = 99;

        int year = LocalDate.now().getYear() - (rand.nextInt(maxAge - minAge + 1) + minAge);
        int month = rand.nextInt(12) + 1;
        int day = rand.nextInt(28) + 1;

        return LocalDate.of(year, month, day);
    }

    public static Person generateRandomPerson(){
        String firstName = getRandomElement(FIRST_NAMES);
        String lastName = getRandomElement(LAST_NAMES);
        LocalDate birthDate = getRandomDate();
        return Person.builder()
            .firstName(firstName)
            .lastName(lastName)
            .birthDate(birthDate)
            .build();
    }
